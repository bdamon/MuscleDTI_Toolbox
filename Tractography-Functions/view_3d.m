function view_3d(anat_image, image_3d_res)

%% preliminary stuff
image_3d_size = size(anat_image);
mask = zeros(image_3d_size);

% mask out outmost rows/columns/slices to allow 2-plane views without interference from tissues
mask(2:(image_3d_size(1)-1), 2:(image_3d_size(2)-1), 2:(image_3d_size(3)-1)) = 1;
anat_image = anat_image.*mask;

%% create figure and GUI

% initialize slice positions at 1/2 the image dimensions
sldr_ax.Value = round(image_3d_size(1)/2);
sldr_sg.Value = round(image_3d_size(3)/2);
sldr_cr.Value = round(image_3d_size(2)/2);

% create figure and locate image plot 
anat_fig = figure('position', [400 50 900 900]);

anat_axes = axes('Parent', anat_fig, ...
    'Units', 'normalized', ...
    'Position', [5/18 7/18 7/18 7/18]);
title(anat_axes, '3D View of DESS Image');

%% UI controls - axial slice

% box around the controls with label
uipanel('Parent', anat_fig, ...
    'BackgroundColor', [.9 .9 .9], ...
    'Units', 'normalized', ...
    'Position', [1/18 .5/18 7/18 2/18])

uicontrol('Parent', anat_fig, ...
    'Style', 'edit', ...
    'Units', 'normalized', ...
    'Position', [1.25/18 1.875/18 6.5/18 .5/18], ...
    'BackgroundColor', [.9 .9 .9], ...
    'String', 'Slice Position Adjustments', ...
    'FontWeight', 'bold', ...
    'FontSize', 9);

%I controls - axial slice
uicontrol('Parent', anat_fig, ...
    'Style', 'edit', ...
    'Units', 'normalized', ...
    'Position', [1.25/18 1.25/18 2/18 .5/18], ...
    'BackgroundColor', [.9 .9 .9], ...
    'String', 'Axial', ...
    'FontWeight', 'bold');

sldr_ax=uicontrol('Parent', anat_fig, ...
    'Style', 'slider', ...
    'Min', 1, ...
    'Max', image_3d_size(1), ...
    'Value', round(image_3d_size(1)/2), ...
    'Units', 'normalized', ...
    'Position', [1.25/18 .75/18 2/18 .5/18], ...
    'BackgroundColor', [.94 .94 .94], ...
    'SliderStep', [1/image_3d_size(1) 6/image_3d_size(1)], ...
    'Callback', @ShowSurface);

% UI controls - coronal slice
uicontrol('Parent', anat_fig, ...
    'Style', 'edit', ...
    'Units', 'normalized', ...
    'Position', [3.5/18 1.25/18 2/18 .5/18], ...
    'BackgroundColor', [.9 .9 .9], ...
    'String', 'Coronal', ...
    'FontWeight', 'bold');

sldr_cr=uicontrol('Parent', anat_fig, ...
    'Style', 'slider', ...
    'Min', 1, ...
    'Max', image_3d_size(2), ...
    'Value', round(image_3d_size(2)/2), ...
    'Units', 'normalized', ...
    'Position', [3.5/18 .75/18 2/18 .5/18], ...
    'BackgroundColor', [.94 .94 .94], ...
    'SliderStep', [1/image_3d_size(2) 6/image_3d_size(2)], ...
    'Callback', @ShowSurface);

% % UI controls - sagittal slice
uicontrol('Parent', anat_fig, ...
    'Style', 'edit', ...
    'Units', 'normalized', ...
    'Position', [5.75/18 1.25/18 2/18 .5/18], ...
    'BackgroundColor', [.9 .9 .9], ...
    'String', 'Sagittal', ...
    'FontWeight', 'bold');

sldr_sg = uicontrol('Parent', anat_fig, ...
    'Style', 'slider', ...
    'Min', 1, ...
    'Max', image_3d_size(3), ...
    'Value', round(image_3d_size(3)/2), ...
    'Units', 'normalized', ...
    'Position', [5.75/18 .75/18 2/18 .5/18], ...
    'BackgroundColor', [.94 .94 .94], ...
    'SliderStep', [1/image_3d_size(3) 6/image_3d_size(3)], ...
    'Callback', @ShowSurface);

%% initial plot

% call plotting function
ShowSurface

% set initial viewing perspective
set(gca, 'CameraPosition', [650 -900 400], ...
    'CameraTarget', [50 80 80], ...
    'CameraUpVector', [0 0 1], ...
    'CameraViewAngle', 5, ...
    'View', [30 15]);

%% Callback functions

function ShowSurface(src, event) %#ok<INUSD> 

% get slice numbers
ax_slice = round(sldr_ax.Value);
sg_slice = round(sldr_sg.Value);
cr_slice = round(sldr_cr.Value);

CameraPosition = anat_axes.CameraPosition;
CameraTarget = anat_axes.CameraTarget;
CameraUpVector = anat_axes.CameraUpVector;
CameraViewAngle = anat_axes.CameraViewAngle;
View = anat_axes.View;

hold off

loop_image_ax = single(squeeze(anat_image(ax_slice, :, :)));
[X_ax, Y_ax] = meshgrid(0:image_3d_res(3):(image_3d_size(3)*image_3d_res(3)-image_3d_res(3)), 0:image_3d_res(2):(image_3d_size(2)*image_3d_res(2)-image_3d_res(2)));
Z_ax = ones(size(loop_image_ax))*ax_slice*image_3d_res(1);

loop_image_sg = single(squeeze(anat_image(:, :, sg_slice)));
[Y_sg, Z_sg] = meshgrid(0:image_3d_res(1):(image_3d_size(1)*image_3d_res(1)-image_3d_res(1)), 0:image_3d_res(2):(image_3d_size(2)*image_3d_res(2)-image_3d_res(2)));
X_sg = ones(size(loop_image_sg))*sg_slice*image_3d_res(3);

loop_image_cr = single(squeeze(anat_image(:, cr_slice, :)));
[X_cr, Z_cr] = meshgrid(0:image_3d_res(3):(image_3d_size(3)*image_3d_res(3)-image_3d_res(3)), 0:image_3d_res(1):(image_3d_size(1)*image_3d_res(1)-image_3d_res(1)));
Y_cr = ones(size(loop_image_cr))*cr_slice*image_3d_res(2);

surf_image_ax = surf(X_ax, Y_ax, Z_ax, loop_image_ax);
set(surf_image_ax, 'facealpha', 1)
colormap('gray')
shading('Interp')
set(gca, 'color', 'k')
hold on

surf_image_sg = surf(X_sg, Y_sg, Z_sg, loop_image_sg);
set(surf_image_sg, 'facealpha', 1)
colormap('gray')
shading('Interp')

surf_image_cr = surf(X_cr, Y_cr, Z_cr, loop_image_cr);
set(surf_image_cr, 'facealpha', 1)
colormap('gray')
shading('Interp')

set(gca, 'CameraPosition', CameraPosition, ...
    'CameraTarget', CameraTarget, ...
    'CameraUpVector', CameraUpVector, ...
    'CameraViewAngle', CameraViewAngle, ...
    'View', View);
axis image

end

%%
end